"""Build backend/data/search/synonyms.jsonl: per CAS, the registry names and synonyms the substance search matches.

Inputs (data, not code): backend/data/search/synonym_sources.json (which DB table/column, tier, citation) and
curated_synonyms.json (cited gap list). terminology.db is opened read-only. Only CAS present in chemical_terms
are written; a curated CAS that is absent fails the build.

Output: line 1 = header {"_about", "built", "sources": {code: {tier, ref[, url]}}};
then one line per CAS: [cas, [[name, source_code], ...]] (a name found in several sources keeps the strongest tier).
Run: python -B scripts/search_synonyms/build_synonyms.py
"""
from __future__ import annotations

import datetime
import json
import os
import re
import sqlite3
import sys

PROJECT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, PROJECT)
from backend.core.chemical_aliases import normalize_alias  # noqa: E402
from backend.core.terminology.synonyms import SEARCH_DATA_DIR, SYNONYMS_FILE, TIER_ORDER  # noqa: E402

TERM_DB = os.path.join(PROJECT, "data", "terminology.db")
_CAS = re.compile(r"^\d{2,7} \d{2} \d$")


def _load(name: str) -> dict:
    with open(os.path.join(SEARCH_DATA_DIR, name), encoding="utf-8") as fh:
        return json.load(fh)


def _names(raw: str | None, spec: dict) -> list[str]:
    out = []
    for part in (raw or "").split(spec["split"]):
        part = part.strip(spec["strip_chars"])
        norm = normalize_alias(part)
        if len(norm) >= 2 and len(part) <= spec["max_name_chars"] and not _CAS.match(norm):
            out.append(part)
    return out


def build(conn: sqlite3.Connection) -> tuple[dict, dict[str, dict[str, list]]]:
    spec = _load("synonym_sources.json")
    curated = _load(spec["curated"]["file"])
    known = {r[0] for r in conn.execute("SELECT DISTINCT cas_no FROM chemical_terms WHERE cas_no <> ''")}
    sources = {s["code"]: {"tier": s["tier"], "ref": s["ref"]} for s in spec["db_sources"]}
    sources.update(curated["sources"])
    by_cas: dict[str, dict[str, list]] = {}

    def add(cas: str, name: str, code: str) -> None:
        names = by_cas.setdefault(cas, {})
        norm = normalize_alias(name)
        old = names.get(norm)
        if old is None or TIER_ORDER.index(sources[code]["tier"]) < TIER_ORDER.index(sources[old[1]]["tier"]):
            names[norm] = [name, code]

    for s in spec["db_sources"]:
        for cas, raw in conn.execute(f'SELECT cas_no, "{s["column"]}" FROM "{s["table"]}"'):
            cas = (cas or "").strip()
            if cas in known:
                for name in _names(raw, spec):
                    add(cas, name, s["code"])
    bad = [it for it in curated["items"] if it["cas"] not in known or it["source"] not in curated["sources"]]
    if bad:
        raise SystemExit(f"{spec['curated']['file']}: CAS not in chemical_terms or unknown source: {bad}")
    for it in curated["items"]:
        add(it["cas"], it["name"], it["source"])
    return sources, by_cas


def main() -> None:
    conn = sqlite3.connect(f"file:{TERM_DB.replace(os.sep, '/')}?mode=ro", uri=True)
    sources, by_cas = build(conn)
    header = {"_about": "generated by scripts/search_synonyms/build_synonyms.py; do not edit",
              "built": datetime.date.today().isoformat(), "sources": sources}
    with open(SYNONYMS_FILE, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(header, ensure_ascii=False) + "\n")
        for cas in sorted(by_cas):
            fh.write(json.dumps([cas, list(by_cas[cas].values())], ensure_ascii=False) + "\n")
    n = sum(len(v) for v in by_cas.values())
    print(f"{len(by_cas)} CAS, {n} names -> {SYNONYMS_FILE} ({os.path.getsize(SYNONYMS_FILE) / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
