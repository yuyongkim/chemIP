"""Fetch PubChem IUPAC name + top synonyms for the benchmark substances and the SEO tier-1 substances only, and write
backend/data/search/pubchem_synonyms.json (curated-file format; every item cites "PubChem CID n").

Raw responses are cached in pubchem_config.CACHE_DIR (E:), so a rerun only asks PubChem for CAS not cached yet.
Run: python -B scripts/search_synonyms/fetch_pubchem_synonyms.py
"""
from __future__ import annotations

import csv
import datetime
import json
import os
import re
import time
import urllib.error
import urllib.request

import pubchem_config as C
from backend.core.chemical_aliases import normalize_alias

_JUNK = [re.compile(p, re.IGNORECASE if i == 0 else 0) for i, p in enumerate(C.JUNK_PATTERNS)]


def targets() -> list[str]:
    with open(C.BENCHMARK_LIST, encoding="utf-8") as fh:
        cas = {it["cas"] for it in json.load(fh)["items"]}
    with open(C.SEO_SELECTION_CSV, encoding="utf-8-sig") as fh:
        cas |= {row["cas"] for row in csv.DictReader(fh) if row["tier"] == C.SEO_TIER}
    if len(cas) > C.MAX_TARGETS:
        raise SystemExit(f"{len(cas)} targets > MAX_TARGETS {C.MAX_TARGETS}: scope is benchmark + SEO tier 1 only")
    return sorted(cas)


def _get(url: str) -> dict:
    req = urllib.request.Request(url, headers={"User-Agent": C.USER_AGENT})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=C.TIMEOUT) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code in (400, 404):
                return {"status": e.code}
            if attempt == 3:
                return {"status": "error"}
        except Exception:  # noqa: BLE001 - transient network error: back off, then give up
            if attempt == 3:
                return {"status": "error"}
        time.sleep(2 * (attempt + 1))
    return {"status": "error"}


def _download(cas: str) -> dict:
    prop = _get(C.PROPERTY_URL.format(cas=cas))
    time.sleep(C.GAP_SECONDS)
    rec: dict = {"cas": cas, "fetched": datetime.date.today().isoformat()}
    if "PropertyTable" not in prop:
        rec["status"] = prop.get("status")
        return rec
    p = prop["PropertyTable"]["Properties"][0]
    rec.update(cid=p.get("CID"), iupac=p.get("IUPACName", ""), title=p.get("Title", ""))
    syn = _get(C.SYNONYMS_URL.format(cid=rec["cid"]))
    time.sleep(C.GAP_SECONDS)
    if "InformationList" not in syn:
        rec["status"] = syn.get("status")
    info = (syn.get("InformationList") or {}).get("Information") or [{}]
    rec["synonyms"] = info[0].get("Synonym", [])
    return rec


def fetch(cas: str) -> dict:
    """Cached raw record {cas, cid, iupac, title, synonyms[]} or {cas, status}. Transient errors are not cached."""
    path = os.path.join(C.CACHE_DIR, f"{cas}.json")
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    rec = _download(cas)
    if rec.get("status") != "error":
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(rec, fh, ensure_ascii=False)
    return rec


def usable(name: str) -> bool:
    return (2 <= len(name) <= C.MAX_NAME_CHARS and re.search(r"[A-Za-z]{2}", name) is not None
            and not any(p.search(name) for p in _JUNK))


def cas_confirmed(rec: dict) -> bool:
    """PubChem resolves some CAS by name search to a different compound (carbon black 1333-86-4 -> methane);
    keep a record only when its CID lists the queried CAS among its own synonyms."""
    return rec["cas"] in rec.get("synonyms", [])


def items_of(rec: dict) -> list[dict]:
    if not rec.get("cid") or not cas_confirmed(rec):
        return []
    cite, out, seen = f"PubChem CID {rec['cid']}", [], set()

    def add(name: str, source: str) -> None:
        norm = normalize_alias(name)
        if norm and norm not in seen and len(name) <= C.MAX_NAME_CHARS:
            seen.add(norm)
            out.append({"name": name, "cas": rec["cas"], "source": source, "cite": cite})

    add(rec.get("iupac", ""), "pubchem_iupac")
    for name in [s for s in rec.get("synonyms", []) if usable(s)][: C.TOP_SYNONYMS]:
        add(name, "pubchem_synonym")
    return out


def document(cas_list: list[str], items: list[dict], misses: list[str]) -> dict:
    return {
        "_about": "generated by scripts/search_synonyms/fetch_pubchem_synonyms.py; do not edit. PubChem IUPAC name and "
                  f"the first {C.TOP_SYNONYMS} usable synonyms (registry numbers and database codes dropped) for the "
                  "substance-search benchmark list and the SEO tier-1 list only, kept only when the CID lists the CAS among its "
                  "synonyms. Each item cites its PubChem CID.",
        "built": datetime.date.today().isoformat(), "targets": len(cas_list), "not_found": misses,
        "sources": {
            "pubchem_iupac": {"tier": "synonym", "derived_from": "pubchem", "url": C.DOCS_URL,
                              "ref": "PubChem PUG REST compound IUPACName (computed by PubChem)"},
            "pubchem_synonym": {"tier": "synonym", "derived_from": "pubchem", "url": C.DOCS_URL,
                                "ref": "PubChem PUG REST compound synonyms (depositor-supplied, first entries)"}},
        "items": items}


def shared_cids(recs: list[dict]) -> set[int]:
    """CIDs that several target CAS resolve to (carbon black and activated carbon -> elemental carbon CID 5462310):
    a generic parent record whose synonyms mix the substances, so none of them gets its names."""
    seen: dict[int, int] = {}
    for rec in recs:
        if rec.get("cid"):
            seen[rec["cid"]] = seen.get(rec["cid"], 0) + 1
    return {cid for cid, n in seen.items() if n > 1}


def miss_reason(rec: dict, shared: set[int]) -> str:
    if rec.get("status"):
        return str(rec["status"])
    if not rec.get("cid"):
        return "no CID"
    if rec["cid"] in shared:
        return f"CID {rec['cid']} shared by several CAS"
    return "CID does not list this CAS"


def main() -> None:
    os.makedirs(C.CACHE_DIR, exist_ok=True)
    cas_list, items, misses = targets(), [], []
    recs = []
    for i, cas in enumerate(cas_list, 1):
        recs.append(fetch(cas))
        if i % 50 == 0:
            print(f"{i}/{len(cas_list)}", flush=True)
    shared = shared_cids(recs)
    for rec in recs:
        got = [] if rec.get("cid") in shared else items_of(rec)
        items += got
        if not got:
            misses.append(f"{rec['cas']} ({miss_reason(rec, shared)})")
    with open(C.OUT_FILE, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(document(cas_list, items, misses), fh, ensure_ascii=False, indent=0)
    print(f"{len(cas_list)} CAS, {len(items)} names, {len(misses)} not found -> {C.OUT_FILE}")


if __name__ == "__main__":
    main()
