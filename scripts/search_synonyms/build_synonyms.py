"""Build backend/data/search/synonyms.jsonl: per CAS, the registry, legal and listed names the substance search matches.

Inputs are data (backend/data/search): synonym_sources.json says which terminology.db columns, which law.go.kr lists
(backend/data/trade_controls/kr_lists) and which curated files (KCIA labels, element names, PubChem names) to read,
with tier and citation; synonym_blocklist.json drops confirmed wrong rows. terminology.db is opened read-only.
Only CAS present in chemical_terms are written; a curated CAS that is absent, or whose English name does not match
its expect_en, fails the build.

Output: line 1 = header {"_about", "built", "sources": {code: {tier, ref[, url, derived_from]}}};
then one line per CAS: [cas, [[name, source_code], ...]].
Run: python -B scripts/search_synonyms/build_synonyms.py
"""
from __future__ import annotations

import datetime
import json
import os
import sqlite3

import spec as S
import checks
import source_curated
import source_db
import source_law
from merge import NameCollector


def build(conn: sqlite3.Connection) -> tuple[dict, NameCollector]:
    spec = S.load(S.SPEC_FILE)
    blocklist = S.load(spec["blocklist"])["items"]
    known = {r[0] for r in conn.execute("SELECT DISTINCT cas_no FROM chemical_terms WHERE cas_no <> ''")}
    sources = source_db.sources(spec)
    law_sources, law_rows = source_law.load(spec["law_lists"], spec)
    cur_sources, cur_items, _ = source_curated.load(spec["curated"])
    sources.update(law_sources)
    sources.update(cur_sources)
    problems = (checks.curated_problems(cur_items, sources, known) + checks.expect_en_problems(conn, cur_items)
                + checks.blocklist_problems(blocklist, sources))
    if problems:
        raise SystemExit("synonym data problems:\n  " + "\n  ".join(problems))
    col = NameCollector(sources, known, blocklist)
    for cas, name, code in source_db.names(conn, spec):
        col.add(cas, name, code)
    for cas, name, code in law_rows:
        col.add(cas, name, code)
    for it in cur_items:
        col.add(it["cas"], it["name"], it["source"])
    col.prune_pubchem_collisions()
    return sources, col


def write(sources: dict, col: NameCollector) -> None:
    used = {code for names in col.by_cas.values() for _, code in names.values()}
    header = {"_about": "generated by scripts/search_synonyms/build_synonyms.py; do not edit",
              "built": datetime.date.today().isoformat(),
              "sources": {c: s for c, s in sorted(sources.items()) if c in used}}
    with open(S.SYNONYMS_FILE, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(header, ensure_ascii=False) + "\n")
        for cas in sorted(col.by_cas):
            fh.write(json.dumps([cas, list(col.by_cas[cas].values())], ensure_ascii=False) + "\n")


def main() -> None:
    conn = sqlite3.connect(f"file:{S.TERM_DB.replace(os.sep, '/')}?mode=ro", uri=True)
    sources, col = build(conn)
    write(sources, col)
    size = os.path.getsize(S.SYNONYMS_FILE) / 1e6
    print(f"{len(col.by_cas)} CAS, {col.count()} names, {col.dropped} blocklisted, "
          f"{col.pubchem_collisions} PubChem names dropped (registry name of another CAS) -> {S.SYNONYMS_FILE} ({size:.1f} MB)")


if __name__ == "__main__":
    main()
