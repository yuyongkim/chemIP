"""Build data/benchmark_cases.json: one case per CAS (SEO seeds + curated list) with its query strings.

Query types (config.QUERY_TYPES): ko (Korean name), en (English common name), iupac (PubChem IUPAC name,
skipped when it equals the common name), cas, alias (curated short/common names, and a seed Korean name that
differs from the curated one). English name: curated > PubChem Title > NCIS/K-REACH name in terminology.db.
Fails if any CAS is absent from chemical_terms.   Run: python build_cases.py
"""
from __future__ import annotations

import json
import sqlite3

import config
from seed_parse import load_seeds


def _norm(s: str) -> str:
    return " ".join((s or "").replace("-", " ").casefold().split())


def _db_english(conn, cas: str) -> str:
    for sql in ("SELECT name_eng FROM ncis_substance WHERE cas_no = ?", "SELECT name_en FROM kreach_chemicals WHERE cas_no = ?"):
        row = conn.execute(sql, (cas,)).fetchone()
        if row and (row[0] or "").strip():
            return row[0].split(";")[0].strip()
    return ""


def build() -> list[dict]:
    with open(config.CURATED, encoding="utf-8") as fh:
        curated = {it["cas"]: it for it in json.load(fh)["items"]}
    with open(config.PUBCHEM_NAMES, encoding="utf-8") as fh:
        pubchem = json.load(fh)["names"]
    seeds = dict(load_seeds())
    conn = sqlite3.connect(f"file:{config.TERM_DB}?mode=ro", uri=True)
    cases, missing = [], []
    for cas in sorted(set(seeds) | set(curated)):
        if not conn.execute("SELECT 1 FROM chemical_terms WHERE cas_no = ? LIMIT 1", (cas,)).fetchone():
            missing.append(cas)
            continue
        cur, pc = curated.get(cas, {}), pubchem.get(cas, {})
        ko = cur.get("ko") or seeds.get(cas, "")
        en = cur.get("en") or pc.get("title") or _db_english(conn, cas)
        iupac = cur["iupac"] if "iupac" in cur else pc.get("iupac", "")
        aliases = list(cur.get("aliases", []))
        if seeds.get(cas) and seeds[cas] != ko:
            aliases.append(seeds[cas])
        queries = {"ko": [ko] if ko else [], "en": [en] if en else [],
                   "iupac": [iupac] if iupac and _norm(iupac) != _norm(en) else [],
                   "cas": [cas], "alias": aliases}
        cases.append({"cas": cas, "origin": "curated" if cur else "seed", "queries": queries,
                      "en_source": "curated" if cur.get("en") else ("pubchem" if pc.get("title") else "terminology.db")})
    if missing:
        raise SystemExit(f"CAS not in chemical_terms: {missing}")
    return cases


def main() -> None:
    cases = build()
    with open(config.CASES, "w", encoding="utf-8") as fh:
        json.dump({"_about": "generated by build_cases.py; do not edit", "cases": cases}, fh, ensure_ascii=False, indent=1)
    counts = {t: sum(len(c["queries"][t]) for c in cases) for t in config.QUERY_TYPES}
    print(f"{len(cases)} cases, queries per type: {counts}")


if __name__ == "__main__":
    main()
