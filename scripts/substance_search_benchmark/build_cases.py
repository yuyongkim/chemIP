"""Build data/benchmark_cases.json: one case per substance of data/common_substances.json with its query strings.

Query types (config.QUERY_TYPES): ko (Korean name), en (English common name), iupac (PubChem IUPAC name; skipped
when absent or equal to the common name), cas, alias (other names the source lists give: KCIA labels such as SM/VCM,
a second list's Korean or English name). Nothing is hand-written here.   Run: python build_cases.py
"""
from __future__ import annotations

import json

import config


def _norm(s: str) -> str:
    return " ".join((s or "").replace("-", " ").casefold().split())


def _case(m: dict, pubchem: dict) -> dict:
    ko, en = m["name_ko"], m["name_en"]
    pc = pubchem.get(m["cas"], {})
    iupac = pc.get("iupac", "")
    seen = {_norm(ko), _norm(en), _norm(m["cas"])}
    aliases = []
    for a in m["aliases"]:
        if a and _norm(a) not in seen:
            seen.add(_norm(a))
            aliases.append(a)
    return {"cas": m["cas"], "categories": m["categories"],
            "queries": {"ko": [ko] if ko else [], "en": [en] if en else [],
                        "iupac": [iupac] if iupac and _norm(iupac) != _norm(en) else [],
                        "cas": [m["cas"]], "alias": aliases}}


def main() -> None:
    with open(config.COMMON, encoding="utf-8") as fh:
        items = json.load(fh)["items"]
    with open(config.PUBCHEM_NAMES, encoding="utf-8") as fh:
        pubchem = json.load(fh)["names"]
    missing_pc = [m["cas"] for m in items if m["cas"] not in pubchem]
    if missing_pc:
        raise SystemExit(f"run fetch_pubchem.py first; {len(missing_pc)} CAS not fetched")
    cases = [_case(m, pubchem) for m in items]
    with open(config.CASES, "w", encoding="utf-8") as fh:
        json.dump({"_about": "generated by build_cases.py; do not edit", "cases": cases}, fh, ensure_ascii=False, indent=1)
    counts = {t: sum(len(c["queries"][t]) for c in cases) for t in config.QUERY_TYPES}
    print(f"{len(cases)} cases, queries per type: {counts}")


if __name__ == "__main__":
    main()
