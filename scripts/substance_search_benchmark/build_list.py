"""Build data/common_substances.json from the four source categories, deduped by CAS (categories merged).

Fields: cas, name_ko, name_en, categories[], source_url[], fetched_date, refs[], aliases[], name_evidence.
Names come from the first category in config.CATEGORY_ORDER that has one; other sourced names become aliases;
names still empty are filled from terminology.db (NCIS / KOSHA / K-REACH) and marked so. Entries whose CAS
cannot be resolved or is absent from chemical_terms go to common_substances_unresolved.json (never dropped silently).
Run: python build_list.py
"""
from __future__ import annotations

import json

import config
from db_names import DbNames
from sources import LOADERS


def _empty(cas: str) -> dict:
    return {"cas": cas, "name_ko": "", "name_en": "", "categories": [], "source_url": [], "fetched_date": "",
            "refs": [], "aliases": [], "name_evidence": {}}


def _merge(m: dict, e: dict, cat: str, evidence: str) -> None:
    if cat not in m["categories"]:
        m["categories"].append(cat)
    if e["source_url"] not in m["source_url"]:
        m["source_url"].append(e["source_url"])
    m["fetched_date"] = max(m["fetched_date"], e["fetched_date"])
    m["refs"].append(e["ref"] + ("" if e.get("cas") else f" -> {evidence}"))
    for field in ("name_ko", "name_en"):
        if e[field] and not m[field]:
            m[field], m["name_evidence"][field] = e[field], cat
        elif e[field] and e[field] != m[field] and e[field] not in m["aliases"]:
            m["aliases"].append(e[field])
    m["aliases"] += [a for a in e["aliases"] if a not in m["aliases"]]


def build(db: DbNames) -> tuple[list[dict], list[dict]]:
    merged: dict[str, dict] = {}
    unresolved: list[dict] = []
    for cat in config.CATEGORY_ORDER:
        entries, skipped = LOADERS[cat](db)
        unresolved += skipped
        for e in entries:
            cas, evidence = (e["cas"], "source list") if e.get("cas") else db.resolve(e["lookup"])
            if not cas:
                unresolved.append({"category": cat, "ref": e["ref"], "why": evidence})
            elif not db.cas_exists(cas):
                unresolved.append({"category": cat, "ref": e["ref"], "cas": cas, "why": "CAS not in chemical_terms"})
            else:
                _merge(merged.setdefault(cas, _empty(cas)), e, cat, evidence)
    for m in merged.values():
        if not m["name_ko"]:
            m["name_ko"], m["name_evidence"]["name_ko"] = db.korean_name(m["cas"]), "terminology.db"
        if not m["name_en"]:
            m["name_en"], m["name_evidence"]["name_en"] = db.english_name(m["cas"]), "terminology.db"
    return sorted(merged.values(), key=lambda m: m["cas"]), unresolved


def main() -> None:
    items, unresolved = build(DbNames())
    with open(config.COMMON, "w", encoding="utf-8") as fh:
        json.dump({"_about": "generated by build_list.py from the sources in config.CATEGORY_ORDER; do not edit",
                   "items": items}, fh, ensure_ascii=False, indent=1)
    with open(config.COMMON_MISSING, "w", encoding="utf-8") as fh:
        json.dump(unresolved, fh, ensure_ascii=False, indent=1)
    by_cat = {c: sum(c in m["categories"] for m in items) for c in config.CATEGORY_ORDER}
    print(f"{len(items)} substances by CAS; per category {by_cat}; unresolved {len(unresolved)}")
    for u in unresolved:
        print("  unresolved:", u)


if __name__ == "__main__":
    main()
